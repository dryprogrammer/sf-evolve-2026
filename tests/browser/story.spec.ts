import { test, expect } from '@playwright/test';
test('caption-only fallback and Needs you action open inspectable source-linked context', async ({page}) => {
 await page.addInitScript(()=>{Object.defineProperty(window,'SpeechSynthesisUtterance',{value:undefined,configurable:true});});
 await page.goto('/');
 await expect(page.getByLabel('Walking as')).toBeEnabled();
 await expect(page.getByRole('heading',{name:'Three perspectives. One human call.'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Voice unavailable',exact:true})).toBeVisible();
 await expect(page.getByText('Fictional · scripted caption',{exact:true})).toHaveCount(3);
 await page.getByRole('button',{name:'Skip to next',exact:true}).click();
 await expect(page.getByText('Caption selected. Voice is off; no information is hidden.',{exact:true})).toBeVisible();
 const attention=page.getByRole('region',{name:'Human attention obligation'});
 await expect(attention).toContainText('Confirmed fixture review state');
 await attention.getByRole('button').click();
 const inspector=page.getByRole('dialog');
 await expect(inspector).toBeVisible();
 await expect(inspector.getByRole('region',{name:'Human attention obligation'})).toContainText('Who:');
 await expect(inspector.getByRole('heading',{name:'Input → judgment → implementation → verification',exact:true})).toBeVisible();
 const seed=inspector.getByRole('link',{name:'Fictional renewal policy · committed source',exact:true});
 await expect(seed).toHaveAttribute('href',/\/blob\/5ba2f24f874ff933fd4000c9c409f7aba38e5cc4\/docs\/scenario\/renewal-policy.md$/);
 await expect(inspector.getByText(/Executable acceptance example:/)).toContainText('standard terms → 20%; custom terms → 15%');
 await expect(inspector.getByRole('link',{name:'Inspect committed seed source',exact:true})).toHaveCount(2);
 await page.keyboard.press('Escape');
 await page.getByRole('link',{name:'Inspect source evidence',exact:false}).click();
 await expect(inspector).toBeVisible();
 const bounds=await inspector.locator('#demo-evidence').boundingBox();
 expect(bounds).not.toBeNull();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
